def build_system_prompt(npc: NpcState, safety: bool = True) -> str:
    """Собрать полный system-промпт под конкретного NPC."""
    role_desc = npc.profile or ROLE_TEMPLATES.get(
        npc.faction.lower(), ROLE_TEMPLATES["neutral"])

    rel = npc.relationship
    if rel >= 60:
        rel_line = f"Ты к игроку относишься очень тепло (отношение {rel}/100): доверяешь, зовёшь «братан»."
    elif rel >= 20:
        rel_line = f"Отношение дружеское ({rel}/100): расположен, но без фанатизма."
    elif rel > -20:
        rel_line = f"Отношение нейтральное ({rel}/100): настороже, смотри по делу."
    elif rel > -60:
        rel_line = f"Отношение холодное/враждебное ({rel}/100): слова режет, руки на автомате."
    else:
        rel_line = f"Отношение ОТВРАТИТЕЛЬНОЕ ({rel}/100): готов стрелять, каждый звук — повод."

    health_line = ""
    if npc.health < 0.45 and not npc.is_dead:
        health_line = "\nТы тяжело ранен: стонешь, говоришь с паузами, тебе нужна помощь."

    parts = [WORLD_SYSTEM]
    if safety:
        parts.append(SAFETY_SUFFIX)
    parts.append(f"""
--- КТО ТЫ ---
Имя: {npc.name}
Фракция: {npc.faction}
Роль/характер: {role_desc}
{health_line}
{rel_line}

--- ТВОЯ ПАМЯТЬ ОБ ИГРОКЕ ---
{(chr(10).join('- ' + f for f in npc.facts[-10:])) or '(пусто: впервые слышишь его голос)'}
""")
    return "\n".join(p for p in parts if p)


def build_messages(npc: NpcState, transcript: str, listeners: list[str],
                   safety: bool = True) -> list[dict]:
    """messages для LLM: system + история диалога + текущая реплика игрока."""
    msgs = [{"role": "system", "content": build_system_prompt(npc, safety)}]

    for h in npc.history[-12:]:
        role = "user" if h["role"] == "player" else "assistant"
        msgs.append({"role": role, "content": h["content"]})

    heard_by = ", ".join(listeners) if listeners else "никто, кроме тебя"
    user_block = (
        f"[Игрок сказал вслух, тебя услышали: {heard_by}. "
        f"Если среди них союзники твоей фракции — они тоже сделают выводы.]\n"
        f"Игрок: {transcript}"
    )
    msgs.append({"role": "user", "content": user_block})
    return msgs


# ---------- реакция «подслушавших» союзников (без отдельного LLM-вызова) ----------
ALLIES_REPLIES = {
    "friendly": ["Верно базаришь, {ally}.", "Молодец, {ally}, по уму молвил.",
                 "{ally}, такие слова одобряю."],
    "offended": ["{ally}, ты чё, берега попутал?", "{ally}, ещё раз — и объясним по-другому.",
                 "Слыхали, братаны? {ally} нас за людей не держит."],
    "aggressive": ["{ally}, совсем озирел! А ну выйди, поговорим.",
                   "{ally}, ты здесь не один такой смелый."],
    "alert_faction": ["Тревога! {ally} нас обижает!", "{ally}, стой где стоишь, руки покажи!"],
}


def ally_reaction(action: str, ally_name: str) -> dict | None:
    """Короткая встроенная реплика союзника, который всё слышал."""
    key = {"friendly": "friendly", "offended": "offended",
           "aggressive": "aggressive", "alert_faction": "alert_faction"}.get(action)
    if not key:
        return None
    import random
    say = random.choice(ALLIES_REPLIES[key]).format(ally=ally_name)
    delta = {"friendly": 2, "offended": -4, "aggressive": -8,
             "alert_faction": -10}[key]
    return {"say": say, "mood_delta": delta, "action": key}
